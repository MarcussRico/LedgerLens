def _tail_arrow(conn):
    """Native DrawingML arrowhead — renders correctly in PowerPoint, Keynote,
    Google Slides and LibreOffice, unlike a hand-drawn triangle."""
    ln = conn.line._get_or_add_ln()
    for tag in ("a:tailEnd",):
        e = ln.find(qn(tag))
        if e is not None:
            ln.remove(e)
    end = ln.makeelement(qn("a:tailEnd"), {"type": "triangle", "w": "sm", "len": "sm"})
    ln.append(end)
    return conn

def arrow(s, x, y, w, color=PAPER_DIM, lw=1.0):
    return _tail_arrow(hline(s, x, y, w, color, lw))

def down_arrow(s, x, y, h, color=PAPER_DIM, lw=1.0):
    return _tail_arrow(vline(s, x, y, h, color, lw))

def text(s, x, y, w, h, runs, size=13, font=SANS, color=PAPER, bold=False,
         align=PP_ALIGN.LEFT, spacing=1.28, anchor=MSO_ANCHOR.TOP, space_after=0,
         caps=False):
    """runs: a string, or a list of (text, {overrides}) tuples, or a list of
    paragraphs where each paragraph is itself such a list."""
    tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    tf.vertical_anchor = anchor

    paras = runs if isinstance(runs, list) and runs and isinstance(runs[0], list) else [runs]
    for i, para in enumerate(paras):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        p.line_spacing = spacing
        p.space_after = Pt(space_after)
        items = para if isinstance(para, list) else [(para, {})]
        for item in items:
            t, ov = item if isinstance(item, tuple) else (item, {})
            if ov.get("caps", caps):
                t = t.upper()
            # A literal \n inside a run is not a line break in DrawingML —
            # PowerPoint would render it as one long wrapped line. Emit real
            # <a:br/> elements instead.
            for j, seg in enumerate(t.split("\n")):
                if j:
                    p.add_line_break()
                r = p.add_run()
                r.text = seg
                f = r.font
                f.name = ov.get("font", font)
                f.size = Pt(ov.get("size", size))
                f.bold = ov.get("bold", bold)
                f.color.rgb = ov.get("color", color)
    return tb

def kicker(s, x, y, t, color=MUTED, size=9.5):
    # letterspacing isn't exposed by python-pptx; thin spaces read the same way
    return text(s, x, y, 8, 0.22, " ".join(t.upper()), size=size, font=MONO, color=color)

def chip(s, x, y, t, color=GOLD, w=None, size=8.5):
    w = w or (0.115 * len(t) + 0.24)
    r = rect(s, x, y, w, 0.235, None, color, 0.6, MSO_SHAPE.ROUNDED_RECTANGLE)
    r.adjustments[0] = 0.5
    text(s, x, y + 0.045, w, 0.2, t.upper(), size=size, font=MONO, color=color, align=PP_ALIGN.CENTER)
    return r


