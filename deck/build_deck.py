ASSETS = "assets"

def new_slide(num=None, kick=None, title=None, bg="content"):
    """bg: which shader-rendered ground to lay down. These are real GLSL
    output rendered through WebGL at 2560x1440 — procedural, deterministic,
    not an image model's guess at what a background looks like."""
    s = prs.slides.add_slide(prs.slide_layouts[6])
    rect(s, 0, 0, W, H, INK)
    s.shapes.add_picture(f"{ASSETS}/bg_{bg}.jpg", 0, 0, Inches(W), Inches(H))
    top = M
    if num is not None:
        text(s, M, top, 1.2, 0.3, f"{num:02d}", size=10, font=MONO, color=MUTED)
    if kick:
        kicker(s, M + 0.62, top + 0.012, kick, GOLD)
    if title:
        text(s, M, top + 0.38, W - 2 * M, 0.6, title, size=31, font=DISPLAY, color=PAPER, spacing=1.02)
        hline(s, M, top + 1.06, W - 2 * M, LINE, 0.9)
    if num is not None:                        # footer only on numbered slides
        hline(s, M, H - 0.46, W - 2 * M, LINE_SOFT, 0.6)
        text(s, M, H - 0.37, 6, 0.24, "LedgerLens · procurement forensics",
             size=8, font=MONO, color=MUTED)
        text(s, W - M - 2, H - 0.37, 2, 0.24, f"{num:02d} / 07", size=8, font=MONO,
             color=MUTED, align=PP_ALIGN.RIGHT)
    return s

